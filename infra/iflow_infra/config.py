"""
Deployment settings for the AWS stack, read from cdk.json → context "iflow" (override any key on the
command line: `cdk deploy -c iflow:alert_email=ops@example.com`).

Validated before anything is synthesized, so a typo fails here with a clear message instead of
half-way through a CloudFormation deployment. Contains no secrets: the JWT signing key and the code
pepper live in Secrets Manager (scripts/create_app_secret.py), and the database password is
generated by RDS.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any, Mapping

_DOMAIN = re.compile(r"^(?=.{4,253}$)([a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$")
_EMAIL = re.compile(r"^[^@\s]+@[^@\s]+\.[a-z]{2,63}$", re.I)
_REGION = re.compile(r"^[a-z]{2}(-gov)?-[a-z]+-\d$")
_ACCOUNT = re.compile(r"^\d{12}$")
_GOOGLE_ID = re.compile(r"^[0-9]+-[a-z0-9]+\.apps\.googleusercontent\.com$")

PLACEHOLDER_EMAIL = "you@example.com"
# Fargate CPU (units) → allowed memory (MiB)
FARGATE_SIZES = {256: (512, 1024, 2048), 512: (1024, 2048, 3072, 4096), 1024: (2048, 3072, 4096, 8192)}
DB_CLASSES = ("t4g.micro", "t4g.small", "t4g.medium", "m7g.large")


class ConfigError(ValueError):
    pass


@dataclass(frozen=True)
class DeployConfig:
    region: str
    account: str | None                    # None: use the CLI profile's account at deploy time
    domain: str                            # iflowcore.com: the SES sender domain
    api_subdomain: str                     # api → api.iflowcore.com
    web_origins: tuple[str, ...]           # browser origins allowed by CORS (the web app)
    alert_email: str                       # alarms + budget notifications
    monthly_budget_usd: int
    google_client_ids: tuple[str, ...]     # empty: Google sign-in off until 10.5
    db_instance_class: str
    db_multi_az: bool
    db_allocated_gb: int
    db_max_gb: int
    backup_days: int
    cpu: int
    memory_mib: int
    min_tasks: int
    max_tasks: int
    jwt_key_id: str
    app_secret_name: str
    log_retention_days: int

    @property
    def api_host(self) -> str:
        return f"{self.api_subdomain}.{self.domain}"

    @property
    def api_url(self) -> str:
        return f"https://{self.api_host}"

    @property
    def mail_from(self) -> str:
        return f"iFlow Core <no-reply@{self.domain}>"

    @property
    def mail_from_domain(self) -> str:
        return f"mail.{self.domain}"

    @classmethod
    def from_context(cls, raw: Mapping[str, Any] | None, *, for_deploy: bool = False) -> DeployConfig:
        r = dict(raw or {})

        def text(key: str, default: str | None = None) -> str:
            value = r.get(key, default)
            if value is None or str(value).strip() == "":
                raise ConfigError(f"iflow:{key} is required")
            return str(value).strip()

        def integer(key: str, default: int, lo: int, hi: int) -> int:
            value = r.get(key, default)
            try:
                n = int(value)
            except (TypeError, ValueError):
                raise ConfigError(f"iflow:{key} must be a whole number") from None
            if isinstance(value, bool) or not lo <= n <= hi:
                raise ConfigError(f"iflow:{key} must be between {lo} and {hi}")
            return n

        def flag(key: str, default: bool) -> bool:
            value = r.get(key, default)
            if isinstance(value, str):
                value = value.strip().lower() in ("1", "true", "yes")
            return bool(value)

        def listed(key: str) -> tuple[str, ...]:
            value = r.get(key) or ()
            if isinstance(value, str):
                value = value.split(",")
            return tuple(str(v).strip() for v in value if str(v).strip())

        region = text("region", "us-east-1")
        if not _REGION.match(region):
            raise ConfigError(f"iflow:region {region!r} isn't an AWS region")
        account = str(r.get("account") or "").strip() or None
        if account and not _ACCOUNT.match(account):
            raise ConfigError("iflow:account must be the 12-digit AWS account id")
        domain = text("domain").lower().rstrip(".")
        if not _DOMAIN.match(domain):
            raise ConfigError(f"iflow:domain {domain!r} isn't a domain name")
        sub = text("api_subdomain", "api").lower()
        if not re.match(r"^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$", sub):
            raise ConfigError("iflow:api_subdomain must be a single DNS label, e.g. api")
        origins = listed("web_origins") or (f"https://{domain}",)
        for origin in origins:
            if not re.match(r"^https://[a-z0-9.-]+(:\d+)?$", origin):
                raise ConfigError(f"iflow:web_origins must be exact https origins (got {origin!r})")
        email = text("alert_email", PLACEHOLDER_EMAIL)
        if not _EMAIL.match(email):
            raise ConfigError("iflow:alert_email isn't an email address")
        if for_deploy and email == PLACEHOLDER_EMAIL:
            raise ConfigError("Set iflow:alert_email in infra/cdk.json (alarms and the budget alert go there)")
        google = listed("google_client_ids")
        for gid in google:
            if not _GOOGLE_ID.match(gid):
                raise ConfigError(f"iflow:google_client_ids: {gid!r} isn't a Google OAuth client id")
        db_class = text("db_instance_class", "t4g.micro")
        if db_class not in DB_CLASSES:
            raise ConfigError(f"iflow:db_instance_class must be one of {DB_CLASSES}")
        cpu = integer("cpu", 256, 256, 1024)
        memory = integer("memory_mib", 512, 512, 8192)
        if cpu not in FARGATE_SIZES or memory not in FARGATE_SIZES[cpu]:
            raise ConfigError(f"Fargate doesn't offer cpu={cpu} with memory_mib={memory}; "
                              f"allowed: {FARGATE_SIZES}")
        min_tasks = integer("min_tasks", 1, 1, 10)
        max_tasks = integer("max_tasks", 3, 1, 20)
        if max_tasks < min_tasks:
            raise ConfigError("iflow:max_tasks must be ≥ min_tasks")
        allocated = integer("db_allocated_gb", 20, 20, 1000)
        max_gb = integer("db_max_gb", 100, 20, 2000)
        if max_gb < allocated:
            raise ConfigError("iflow:db_max_gb must be ≥ db_allocated_gb")
        key_id = text("jwt_key_id", "k1")
        if not re.match(r"^[A-Za-z0-9_-]{1,32}$", key_id):
            raise ConfigError("iflow:jwt_key_id: letters, digits, _ and - only")
        secret_name = text("app_secret_name", "iflow-core/api/app")
        retention = integer("log_retention_days", 30, 1, 3653)
        if retention not in (1, 3, 5, 7, 14, 30, 60, 90, 120, 150, 180, 365, 400, 545, 731, 1096, 1827, 2192,
                             2557, 2922, 3288, 3653):
            raise ConfigError("iflow:log_retention_days must be a CloudWatch retention value (e.g. 30, 90, 365)")
        return cls(region=region, account=account, domain=domain, api_subdomain=sub, web_origins=origins,
                   alert_email=email, monthly_budget_usd=integer("monthly_budget_usd", 80, 10, 100_000),
                   google_client_ids=google, db_instance_class=db_class, db_multi_az=flag("db_multi_az", False),
                   db_allocated_gb=allocated, db_max_gb=max_gb, backup_days=integer("backup_days", 7, 1, 35),
                   cpu=cpu, memory_mib=memory, min_tasks=min_tasks, max_tasks=max_tasks, jwt_key_id=key_id,
                   app_secret_name=secret_name, log_retention_days=retention)

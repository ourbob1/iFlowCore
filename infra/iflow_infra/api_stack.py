"""
iFlow Core sync API on AWS (Phase 10.4).

    Internet ──HTTPS──▶ ALB (+ WAF) ──▶ ECS Fargate: api/ container ──TLS──▶ RDS PostgreSQL
                          ▲ ACM cert                   │  Secrets Manager: JWT key, code pepper, DB login
                          │                            └─▶ SES (verification / reset email)
                  api.<domain> CNAME (your DNS host)

Design choices
  • No NAT gateway (≈US$32/month saved): the API tasks run in public subnets with a public IP but
    their security group accepts traffic only from the load balancer. The database lives in
    isolated subnets with no route to or from the internet and accepts only the API's security group.
  • Secrets never touch the template, the image or the app binaries: ECS injects them from Secrets
    Manager at start. The DB password is generated by RDS; the JWT key and pepper by
    scripts/create_app_secret.py.
  • Migrations run once per new image, before the service updates (a CDK trigger → one-off ECS task).
  • The server only ever sees ciphertext for synced data (E2E, Phase 10.3). Logs are request
    metadata; WAF request sampling is off because samples would include Authorization headers.
  • DNS stays with your current provider: `scripts/dns_records.py` prints the records to add.
"""

from __future__ import annotations

from pathlib import Path

import aws_cdk as cdk
from aws_cdk import (
    Duration,
    RemovalPolicy,
    aws_budgets as budgets,
    aws_certificatemanager as acm,
    aws_cloudwatch as cw,
    aws_cloudwatch_actions as cw_actions,
    aws_ec2 as ec2,
    aws_ecr_assets as ecr_assets,
    aws_ecs as ecs,
    aws_elasticloadbalancingv2 as elbv2,
    aws_iam as iam,
    aws_lambda as lambda_,
    aws_logs as logs,
    aws_rds as rds,
    aws_secretsmanager as sm,
    aws_ses as ses,
    aws_sns as sns,
    aws_sns_subscriptions as subs,
    aws_wafv2 as waf,
    triggers,
)
from constructs import Construct

from .config import DeployConfig

API_DIR = Path(__file__).resolve().parents[2] / "api"
TRIGGER_DIR = Path(__file__).resolve().parent / "migrate_trigger"
CONTAINER_PORT = 8080
DB_NAME = "iflow"
INTEGRATION_CLIENTS_SECRET = "iflow-core/api/integration-clients"
_RETENTION = {1: "ONE_DAY", 3: "THREE_DAYS", 5: "FIVE_DAYS", 7: "ONE_WEEK", 14: "TWO_WEEKS", 30: "ONE_MONTH",
              60: "TWO_MONTHS", 90: "THREE_MONTHS", 120: "FOUR_MONTHS", 150: "FIVE_MONTHS", 180: "SIX_MONTHS",
              365: "ONE_YEAR", 400: "THIRTEEN_MONTHS", 545: "EIGHTEEN_MONTHS", 731: "TWO_YEARS",
              1096: "THREE_YEARS", 1827: "FIVE_YEARS", 2192: "SIX_YEARS", 2557: "SEVEN_YEARS",
              2922: "EIGHT_YEARS", 3288: "NINE_YEARS", 3653: "TEN_YEARS"}


class ApiStack(cdk.Stack):
    def __init__(self, scope: Construct, construct_id: str, *, cfg: DeployConfig, **kwargs) -> None:
        super().__init__(scope, construct_id, termination_protection=True,
                         description="iFlow Core account & E2E sync API (Phase 10.4)", **kwargs)
        self.cfg = cfg
        cdk.Tags.of(self).add("project", "iflow-core")
        cdk.Tags.of(self).add("component", "sync-api")
        retention = getattr(logs.RetentionDays, _RETENTION[cfg.log_retention_days])

        # --- network ------------------------------------------------------------------------------
        self.vpc = ec2.Vpc(self, "Vpc", max_azs=2, nat_gateways=0, restrict_default_security_group=True,
                           subnet_configuration=[
                               ec2.SubnetConfiguration(name="public", subnet_type=ec2.SubnetType.PUBLIC,
                                                       cidr_mask=24),
                               ec2.SubnetConfiguration(name="db", subnet_type=ec2.SubnetType.PRIVATE_ISOLATED,
                                                       cidr_mask=24)])
        self.api_sg = ec2.SecurityGroup(self, "ApiSg", vpc=self.vpc, allow_all_outbound=True,
                                        description="iFlow API tasks: inbound from the load balancer only")
        self.db_sg = ec2.SecurityGroup(self, "DbSg", vpc=self.vpc, allow_all_outbound=False,
                                       description="iFlow database: inbound from the API tasks only")
        self.db_sg.add_ingress_rule(self.api_sg, ec2.Port.tcp(5432), "PostgreSQL from the API tasks")

        # --- database -----------------------------------------------------------------------------
        engine = rds.DatabaseInstanceEngine.postgres(version=rds.PostgresEngineVersion.VER_16)
        params = rds.ParameterGroup(self, "DbParams", engine=engine, description="iFlow: TLS only",
                                    parameters={"rds.force_ssl": "1", "password_encryption": "scram-sha-256"})
        self.db = rds.DatabaseInstance(
            self, "Db", engine=engine, instance_type=ec2.InstanceType(cfg.db_instance_class), vpc=self.vpc,
            vpc_subnets=ec2.SubnetSelection(subnet_type=ec2.SubnetType.PRIVATE_ISOLATED),
            security_groups=[self.db_sg], publicly_accessible=False, parameter_group=params,
            credentials=rds.Credentials.from_generated_secret("iflow", secret_name="iflow-core/api/db"),
            database_name=DB_NAME, multi_az=cfg.db_multi_az, storage_type=rds.StorageType.GP3,
            allocated_storage=cfg.db_allocated_gb, max_allocated_storage=cfg.db_max_gb, storage_encrypted=True,
            backup_retention=Duration.days(cfg.backup_days), preferred_backup_window="07:00-07:30",
            preferred_maintenance_window="sun:08:00-sun:08:30", copy_tags_to_snapshot=True,
            deletion_protection=True, removal_policy=RemovalPolicy.SNAPSHOT, auto_minor_version_upgrade=True,
            enable_performance_insights=False, ca_certificate=rds.CaCertificate.RDS_CA_RSA2048_G1)

        # --- secrets ------------------------------------------------------------------------------
        app_secret = sm.Secret.from_secret_name_v2(self, "AppSecret", cfg.app_secret_name)
        # OAuth client secrets for platform integrations (token broker): JSON, "{}" until Uber approves iFlow
        clients_secret = sm.Secret.from_secret_name_v2(self, "IntegrationClients", INTEGRATION_CLIENTS_SECRET)
        secrets = {
            "IFLOW_API_DATABASE_SECRET": ecs.Secret.from_secrets_manager(self.db.secret),   # whole JSON
            "IFLOW_API_JWT_PRIVATE_KEY": ecs.Secret.from_secrets_manager(app_secret, "jwt_private_key"),
            "IFLOW_API_CODE_PEPPER": ecs.Secret.from_secrets_manager(app_secret, "code_pepper"),
            "IFLOW_API_INTEGRATION_CLIENTS": ecs.Secret.from_secrets_manager(clients_secret),
        }
        environment = {
            "IFLOW_API_ENV": "production",
            "IFLOW_API_MAIL_BACKEND": "ses",
            "IFLOW_API_MAIL_FROM": cfg.mail_from,
            "IFLOW_API_SES_REGION": cfg.region,
            "IFLOW_API_TRUST_PROXY": "true",
            "IFLOW_API_CORS_ORIGINS": ",".join(cfg.web_origins),
            "IFLOW_API_GOOGLE_CLIENT_IDS": ",".join(cfg.google_client_ids),
            "IFLOW_API_JWT_KEY_ID": cfg.jwt_key_id,
        }

        # --- containers ---------------------------------------------------------------------------
        self.image = ecr_assets.DockerImageAsset(
            self, "ApiImage", directory=str(API_DIR), platform=ecr_assets.Platform.LINUX_AMD64,
            exclude=["**/__pycache__", "*.db", "*.sqlite", ".pytest_cache", ".venv", "docker-compose.yml"])
        image = ecs.ContainerImage.from_docker_image_asset(self.image)
        self.cluster = ecs.Cluster(self, "Cluster", vpc=self.vpc)
        platform = ecs.RuntimePlatform(cpu_architecture=ecs.CpuArchitecture.X86_64,
                                       operating_system_family=ecs.OperatingSystemFamily.LINUX)

        api_logs = logs.LogGroup(self, "ApiLogs", log_group_name="/iflow-core/api", retention=retention,
                                 removal_policy=RemovalPolicy.RETAIN)
        self.task = ecs.FargateTaskDefinition(self, "ApiTask", cpu=cfg.cpu, memory_limit_mib=cfg.memory_mib,
                                              runtime_platform=platform)
        self.task.add_container(
            "api", image=image, environment=environment, secrets=secrets,
            port_mappings=[ecs.PortMapping(container_port=CONTAINER_PORT)],
            logging=ecs.LogDrivers.aws_logs(stream_prefix="api", log_group=api_logs))

        migrate_logs = logs.LogGroup(self, "MigrateLogs", log_group_name="/iflow-core/api/migrate",
                                     retention=retention, removal_policy=RemovalPolicy.RETAIN)
        self.migrate_task = ecs.FargateTaskDefinition(self, "MigrateTask", cpu=256, memory_limit_mib=512,
                                                      runtime_platform=platform)
        self.migrate_task.add_container(
            "migrate", image=image, environment=environment, secrets=secrets, command=["alembic", "upgrade", "head"],
            logging=ecs.LogDrivers.aws_logs(stream_prefix="migrate", log_group=migrate_logs))

        # email: only the API task may send, only as no-reply@<domain>
        self.mail = ses.EmailIdentity(self, "MailIdentity", identity=ses.Identity.domain(cfg.domain),
                                      mail_from_domain=cfg.mail_from_domain,
                                      mail_from_behavior_on_mx_failure=ses.MailFromBehaviorOnMxFailure.USE_DEFAULT_VALUE)
        self.task.task_role.add_to_principal_policy(iam.PolicyStatement(
            actions=["ses:SendEmail", "ses:SendRawEmail"],
            resources=[self.format_arn(service="ses", resource="identity", resource_name=cfg.domain),
                       self.format_arn(service="ses", resource="identity", resource_name="*")],
            conditions={"StringEquals": {"ses:FromAddress": f"no-reply@{cfg.domain}"}}))

        self.service = ecs.FargateService(
            self, "ApiService", cluster=self.cluster, task_definition=self.task, desired_count=cfg.min_tasks,
            assign_public_ip=True, vpc_subnets=ec2.SubnetSelection(subnet_type=ec2.SubnetType.PUBLIC),
            security_groups=[self.api_sg], min_healthy_percent=100, max_healthy_percent=200,
            circuit_breaker=ecs.DeploymentCircuitBreaker(rollback=True),
            health_check_grace_period=Duration.seconds(60))
        if cfg.max_tasks > cfg.min_tasks:
            scaling = self.service.auto_scale_task_count(min_capacity=cfg.min_tasks, max_capacity=cfg.max_tasks)
            scaling.scale_on_cpu_utilization("Cpu", target_utilization_percent=60,
                                             scale_in_cooldown=Duration.minutes(5),
                                             scale_out_cooldown=Duration.minutes(1))

        # --- migrations before every new image ------------------------------------------------------
        public_subnets = self.vpc.select_subnets(subnet_type=ec2.SubnetType.PUBLIC).subnet_ids
        self.migrate_fn = triggers.TriggerFunction(
            self, "Migrate", runtime=lambda_.Runtime.PYTHON_3_12, handler="index.handler",
            code=lambda_.Code.from_asset(str(TRIGGER_DIR)), timeout=Duration.minutes(14),
            description="Runs alembic upgrade head in a one-off ECS task before the API updates",
            environment={"CLUSTER": self.cluster.cluster_name,
                         "TASK_DEFINITION": self.migrate_task.task_definition_arn,
                         "SUBNETS": cdk.Fn.to_json_string(public_subnets),
                         "SECURITY_GROUP": self.api_sg.security_group_id,
                         "IMAGE": self.image.image_uri},        # new image → new version → runs again
            execute_after=[self.db], execute_before=[self.service], execute_on_handler_change=True)
        self.migrate_task.grant_run(self.migrate_fn)
        self.migrate_fn.add_to_role_policy(iam.PolicyStatement(
            actions=["ecs:DescribeTasks"], resources=["*"],
            conditions={"ArnEquals": {"ecs:cluster": self.cluster.cluster_arn}}))
        logs.LogRetention(self, "MigrateFnLogs", log_group_name=f"/aws/lambda/{self.migrate_fn.function_name}",
                          retention=retention)

        # --- load balancer, TLS ---------------------------------------------------------------------
        self.certificate = acm.Certificate(self, "ApiCert", domain_name=cfg.api_host,
                                           validation=acm.CertificateValidation.from_dns())
        self.alb = elbv2.ApplicationLoadBalancer(
            self, "Alb", vpc=self.vpc, internet_facing=True, drop_invalid_header_fields=True,
            vpc_subnets=ec2.SubnetSelection(subnet_type=ec2.SubnetType.PUBLIC))
        https = self.alb.add_listener("Https", port=443, certificates=[self.certificate],
                                      ssl_policy=elbv2.SslPolicy.RECOMMENDED_TLS, open=True)
        self.target_group = https.add_targets(
            "Api", port=CONTAINER_PORT, protocol=elbv2.ApplicationProtocol.HTTP, targets=[self.service],
            deregistration_delay=Duration.seconds(20),
            health_check=elbv2.HealthCheck(path="/healthz", healthy_http_codes="200", interval=Duration.seconds(15),
                                           healthy_threshold_count=2, unhealthy_threshold_count=3))
        self.alb.add_redirect(source_port=80, target_port=443)

        self._waf()
        self._alarms_and_budget()
        self._outputs()

    # -- WAF ---------------------------------------------------------------------------------------------

    def _waf(self) -> None:
        def visibility(name: str) -> waf.CfnWebACL.VisibilityConfigProperty:
            # sampling off: samples would store request headers, i.e. bearer tokens
            return waf.CfnWebACL.VisibilityConfigProperty(cloud_watch_metrics_enabled=True, metric_name=name,
                                                          sampled_requests_enabled=False)

        def rate_rule(name: str, priority: int, limit: int, path_prefix: str | None) -> waf.CfnWebACL.RuleProperty:
            scope = None
            if path_prefix:
                scope = waf.CfnWebACL.StatementProperty(byte_match_statement=waf.CfnWebACL.ByteMatchStatementProperty(
                    search_string=path_prefix, positional_constraint="STARTS_WITH",
                    field_to_match=waf.CfnWebACL.FieldToMatchProperty(uri_path={}),
                    text_transformations=[waf.CfnWebACL.TextTransformationProperty(priority=0, type="NONE")]))
            return waf.CfnWebACL.RuleProperty(
                name=name, priority=priority, action=waf.CfnWebACL.RuleActionProperty(block={}),
                visibility_config=visibility(name),
                statement=waf.CfnWebACL.StatementProperty(rate_based_statement=waf.CfnWebACL.RateBasedStatementProperty(
                    limit=limit, aggregate_key_type="IP", evaluation_window_sec=300, scope_down_statement=scope)))

        def managed(name: str, priority: int, overrides: tuple[str, ...] = ()) -> waf.CfnWebACL.RuleProperty:
            return waf.CfnWebACL.RuleProperty(
                name=name, priority=priority, override_action=waf.CfnWebACL.OverrideActionProperty(none={}),
                visibility_config=visibility(name),
                statement=waf.CfnWebACL.StatementProperty(managed_rule_group_statement=waf.CfnWebACL.ManagedRuleGroupStatementProperty(
                    vendor_name="AWS", name=name,
                    rule_action_overrides=[waf.CfnWebACL.RuleActionOverrideProperty(
                        name=o, action_to_use=waf.CfnWebACL.RuleActionProperty(count={})) for o in overrides] or None)))

        self.web_acl = waf.CfnWebACL(
            self, "WebAcl", scope="REGIONAL", default_action=waf.CfnWebACL.DefaultActionProperty(allow={}),
            visibility_config=visibility("iflow-api"), description="iFlow API: rate limits + AWS managed rules",
            rules=[
                rate_rule("rate-auth", 0, 100, "/v1/auth/"),          # sign-in / sign-up / codes per IP / 5 min
                rate_rule("rate-all", 1, 2000, None),
                managed("AWSManagedRulesAmazonIpReputationList", 2),
                # encrypted sync batches are legitimately larger than the 8 KB body rule allows
                managed("AWSManagedRulesCommonRuleSet", 3, ("SizeRestrictions_BODY",)),
                managed("AWSManagedRulesKnownBadInputsRuleSet", 4),
            ])
        waf.CfnWebACLAssociation(self, "WebAclAlb", resource_arn=self.alb.load_balancer_arn,
                                 web_acl_arn=self.web_acl.attr_arn)

    # -- alarms & budget ----------------------------------------------------------------------------------

    def _alarms_and_budget(self) -> None:
        cfg = self.cfg
        topic = sns.Topic(self, "Alerts", display_name="iFlow Core alerts")
        topic.add_subscription(subs.EmailSubscription(cfg.alert_email))
        action = cw_actions.SnsAction(topic)
        minute = Duration.minutes(1)
        alarms = [
            cw.Alarm(self, "ApiDown", alarm_description="No healthy API tasks behind the load balancer",
                     metric=self.target_group.metrics.healthy_host_count(period=minute, statistic="Minimum"),
                     threshold=1, comparison_operator=cw.ComparisonOperator.LESS_THAN_THRESHOLD,
                     evaluation_periods=3, treat_missing_data=cw.TreatMissingData.BREACHING),
            cw.Alarm(self, "Api5xx", alarm_description="API returned server errors",
                     metric=self.target_group.metrics.http_code_target(elbv2.HttpCodeTarget.TARGET_5XX_COUNT,
                                                                       period=Duration.minutes(5), statistic="Sum"),
                     threshold=10, evaluation_periods=1, treat_missing_data=cw.TreatMissingData.NOT_BREACHING),
            cw.Alarm(self, "ApiSlow", alarm_description="p95 latency above 2 s",
                     metric=self.target_group.metrics.target_response_time(period=Duration.minutes(5), statistic="p95"),
                     threshold=2, evaluation_periods=3, treat_missing_data=cw.TreatMissingData.NOT_BREACHING),
            cw.Alarm(self, "DbCpu", alarm_description="Database CPU above 80 %",
                     metric=self.db.metric_cpu_utilization(period=Duration.minutes(5)), threshold=80,
                     evaluation_periods=3),
            cw.Alarm(self, "DbStorage", alarm_description="Database has under 2 GiB free",
                     metric=self.db.metric_free_storage_space(period=Duration.minutes(5)), threshold=2 * 1024 ** 3,
                     comparison_operator=cw.ComparisonOperator.LESS_THAN_THRESHOLD, evaluation_periods=1),
        ]
        for alarm in alarms:
            alarm.add_alarm_action(action)
            alarm.add_ok_action(action)

        subscriber = [budgets.CfnBudget.SubscriberProperty(address=cfg.alert_email, subscription_type="EMAIL")]
        budgets.CfnBudget(self, "Budget", budget=budgets.CfnBudget.BudgetDataProperty(
            budget_name="iflow-core-monthly", budget_type="COST", time_unit="MONTHLY",
            budget_limit=budgets.CfnBudget.SpendProperty(amount=cfg.monthly_budget_usd, unit="USD")),
            notifications_with_subscribers=[
                budgets.CfnBudget.NotificationWithSubscribersProperty(
                    notification=budgets.CfnBudget.NotificationProperty(
                        comparison_operator="GREATER_THAN", notification_type=kind, threshold=pct,
                        threshold_type="PERCENTAGE"), subscribers=subscriber)
                for kind, pct in (("ACTUAL", 80), ("FORECASTED", 100))])

    # -- outputs --------------------------------------------------------------------------------------------

    def _outputs(self) -> None:
        cfg = self.cfg
        cdk.CfnOutput(self, "ApiUrl", value=cfg.api_url, description="Set this as the sync server in the apps")
        cdk.CfnOutput(self, "DnsApiCname", value=f"{cfg.api_host} CNAME {self.alb.load_balancer_dns_name}",
                      description="Add at your DNS host")
        for i, record in enumerate(self.mail.dkim_records, start=1):
            cdk.CfnOutput(self, f"DnsDkim{i}", value=cdk.Fn.join(" ", [record.name, "CNAME", record.value]),
                          description="SES DKIM: add at your DNS host")
        cdk.CfnOutput(self, "DnsMailFromMx",
                      value=f"{cfg.mail_from_domain} MX 10 feedback-smtp.{cfg.region}.amazonses.com")
        cdk.CfnOutput(self, "DnsMailFromSpf", value=f'{cfg.mail_from_domain} TXT "v=spf1 include:amazonses.com ~all"')
        cdk.CfnOutput(self, "CertificateArn", value=self.certificate.certificate_arn)
        cdk.CfnOutput(self, "DbSecretName", value="iflow-core/api/db", description="Generated by RDS; never printed")
        cdk.CfnOutput(self, "LoadBalancerDns", value=self.alb.load_balancer_dns_name)
